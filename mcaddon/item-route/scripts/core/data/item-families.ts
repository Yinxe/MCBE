/**
 * ============================================================================
 * ItemFamilies —— 物品族数据（同族归纳）
 * ============================================================================
 *
 * 机制：一族一个开关。仓库级可启用的家族全集，玩家在仓库设置→同族配置里逐族开关；
 * 容器级可将某个多物容器绑定到一个族，该容器即收纳族内全部物品。
 *
 * 约定（审查）：
 *   · 每个物品**至多属于一族**（族间互斥）——`FAMILY_BY_ITEM` 反向映射时后写覆盖先写，
 *     但数据应保证不重复（tests 有核验）。
 *   · 数据纯静态、零 @minecraft 依赖，可入 core 单测。
 *   · 物品宇宙以 core/data 的全量 itemId 为准（1.21.94 世代）；族内 id 应落在其内。
 *   · 手工维护（2026-08 重组：圆木/菌类分开、植物/树苗/树叶、农/食、原生自然方块、
 *     末地专属、稀有合并、宠物装备、其他材料）。
 * ============================================================================
 */

